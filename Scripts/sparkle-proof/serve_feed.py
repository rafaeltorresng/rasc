#!/usr/bin/env python3
"""Serve a Sparkle proof feed over HTTPS.

Usage:
    Scripts/sparkle-proof/serve_feed.py <feed-dir> [port] [cert-chain] [key]

The default certificate paths match the files generated by the proof commands
in README.md. Sparkle only trusts this feed after the test CA is explicitly
trusted in the login or System keychain; curl can use --cacert without changing
system trust.
"""

from __future__ import annotations

import http.server
import os
import ssl
import sys


def main() -> int:
    root = os.path.abspath(sys.argv[1] if len(sys.argv) > 1 else "build/sparkle-proof/feed")
    port = int(sys.argv[2] if len(sys.argv) > 2 else "8443")
    certificate = os.path.abspath(
        sys.argv[3] if len(sys.argv) > 3 else "build/sparkle-proof/tls/server-chain.pem"
    )
    key = os.path.abspath(
        sys.argv[4] if len(sys.argv) > 4 else "build/sparkle-proof/tls/server-key.pem"
    )

    class Handler(http.server.SimpleHTTPRequestHandler):
        def __init__(self, *args, **kwargs):
            super().__init__(*args, directory=root, **kwargs)

        def log_message(self, fmt, *args):
            sys.stderr.write("%s - %s\n" % (self.address_string(), fmt % args))
            sys.stderr.flush()

    server = http.server.ThreadingHTTPServer(("127.0.0.1", port), Handler)
    context = ssl.SSLContext(ssl.PROTOCOL_TLS_SERVER)
    context.load_cert_chain(certfile=certificate, keyfile=key)
    server.socket = context.wrap_socket(server.socket, server_side=True)
    print(f"serving {root} at https://127.0.0.1:{port}/", flush=True)
    server.serve_forever()
    return 0


if __name__ == "__main__":
    sys.exit(main())
